#!/usr/bin/env python3
"""KlipperXL-Plus config generator (docs/RELEASE_CONFIG.md).

  kxlplus_config.py tools --tools 0,1,2 --out ~/printer_data/config/kxlplus
      write kxlplus/tools/tN.cfg for each listed tool (installer-owned, replaced
      freely) and copy the shared xl_base.cfg next to them.

  kxlplus_config.py printer-cfg --tools 0,1,2 --mcu-serial /dev/serial/by-id/...
                                --out ~/printer_data/config/printer.cfg
      create the USER-OWNED printer.cfg: includes, [mcu] serial, and the seeded
      values Klipper requires or a user may recalibrate (heater PID, loadcell
      counts_per_gram).  REFUSES to overwrite an existing file.

  kxlplus_config.py klipperscreen --conf ~/printer_data/config/KlipperScreen.conf
      KlipperScreen's Cooldown only zeroes Klipper heaters and the modular bed
      is not one: ADD a [preheat cooldown] that runs M140 S0 (KlipperScreen
      docs/Configuration.md "special preheat setting named cooldown").  Only
      adds; a [preheat cooldown] of the user's is left as it is.

Tool T{N} = Dwarf {D} = N+1 (Prusa numbering), MCU dwarf_t{N}.  Tools are always
included in ascending order: the bridge brings the Dwarfs up in [mcu] section
order, so they boot T0 -> T4 (owner, 2026-10-03).
"""
import argparse, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(HERE, "tool_template.cfg")
RELEASE = os.path.join(HERE, "..", "release", "kxlplus")
# installer-owned shared files (xl_led_effects.cfg is only [include]d by the
# user, it needs the klipper-led_effect plugin)
SHARED = ("xl_base.cfg", "xl_macros.cfg", "xl_pa_tuner.cfg",
          "xl_led_effects.cfg", "bedlet_grid.html")
# Prusa defaults, seeded once into printer.cfg (Configuration_XL_Dwarf.h l.163;
# common/loadcell.hpp:260-261 scale 0.0192 g/count)
PID_SEED = (14.0, 1.0, 100.0)
COUNTS_PER_GRAM_SEED = 52.083
# Released KlipperXL starting points (config/printer.cfg @1b681b3), generic -
# never the owner's measured values (docs/RELEASE_CONFIG.md):
#   pressure_advance 0.025 ([extruder] l.562; PA_TUNE_Tn measures each tool)
#   input shaper = stock Prusa XL factory defaults, shipped enabled (l.653-673;
#   input_shaper_config.hpp XL branch: mzv 35.8 / 35.4, damping 0.1 = Klipper's
#   default) - stock only runs its accelerations with shaping on
PA_SEED = 0.025
SHAPER_SEED = (("x", "mzv", 35.8), ("y", "mzv", 35.4))


def ext_name(n):
    return "extruder" if n == 0 else "extruder%d" % n


def parse_tools(s):
    tools = sorted(set(int(t) for t in s.replace(" ", "").split(",") if t != ""))
    if not tools or any(t < 0 or t > 4 for t in tools):
        raise SystemExit("tools must be 0-4, e.g. 0,1,2")
    return tools


def tool_cfg(n):
    tpl = open(TEMPLATE).read()
    out = (tpl.replace("{N}", str(n)).replace("{D}", str(n + 1))
           .replace("{EXT}", ext_name(n)))
    return ("# GENERATED by kxlplus_config.py from tool_template.cfg - edit the"
            " template, not this file\n" + out)


def cmd_tools(args):
    tools = parse_tools(args.tools)
    tdir = os.path.join(args.out, "tools")
    os.makedirs(tdir, exist_ok=True)
    for n in range(5):
        path = os.path.join(tdir, "t%d.cfg" % n)
        if n in tools:
            with open(path, "w") as f:
                f.write(tool_cfg(n))
            print("wrote %s" % path)
        elif os.path.exists(path):
            os.remove(path)          # a tool that is no longer detected
            print("removed %s" % path)
    for name in SHARED:
        src, dst = os.path.join(RELEASE, name), os.path.join(args.out, name)
        if not (os.path.exists(dst) and os.path.samefile(src, dst)):
            shutil.copyfile(src, dst)
            print("wrote %s" % dst)


def printer_cfg_text(tools, mcu_serial, frontend):
    lines = [
        "# printer.cfg - YOURS.  The KlipperXL-Plus installer creates this once and never",
        "# rewrites it.  Calibrations live here and in the SAVE_CONFIG block below",
        "# (docs/RELEASE_CONFIG.md).  kxlplus/*.cfg are replaced on every update.",
        "",
        "[mcu]",
        "serial: %s" % (mcu_serial,),
        "restart_method: command",
        "",
        "[include kxlplus/xl_base.cfg]",
        "# tools, ascending (the Dwarfs boot in this order)",
    ]
    lines += ["[include kxlplus/tools/t%d.cfg]" % n for n in tools]
    lines += ["", "[include %s.cfg]" % (frontend,), "",
              "# Side LED animations - needs the klipper-led_effect plugin",
              "# (github.com/julianschill/klipper-led_effect); Klipper will not",
              "# start with this line and no plugin.",
              "#[include kxlplus/xl_led_effects.cfg]", "",
              "# --- seeded starting values (Prusa / released KlipperXL defaults, not",
              "# --- measured on any printer): PID_CALIBRATE, the load cell reference,",
              "# --- PA_TUNE_Tn and SHAPER_CALIBRATE replace them via SAVE_CONFIG.", ""]
    # control too: PID_CALIBRATE saves control + pid_Kp/Ki/Kd, so none of the
    # four may be set in an installer-owned include (SAVE_CONFIG conflict)
    for n in tools:
        lines += ["[%s]" % ext_name(n), "control: pid",
                  "pid_Kp: %.3f" % PID_SEED[0], "pid_Ki: %.3f" % PID_SEED[1],
                  "pid_Kd: %.3f" % PID_SEED[2],
                  "pressure_advance: %.3f" % PA_SEED, ""]
    for n in tools:
        lines += ["[xl_load_cell_probe T%d]" % n,
                  "counts_per_gram: %.3f" % COUNTS_PER_GRAM_SEED, ""]
    lines += ["# stock Prusa XL input shaper (factory defaults)", "[input_shaper]"]
    for axis, kind, freq in SHAPER_SEED:
        lines += ["shaper_type_%s: %s" % (axis, kind),
                  "shaper_freq_%s: %.1f" % (axis, freq)]
    lines += [""]
    return "\n".join(lines) + "\n"


def cmd_printer_cfg(args):
    if os.path.exists(args.out):
        raise SystemExit("REFUSING: %s exists - printer.cfg is yours, the"
                         " installer never overwrites it" % (args.out,))
    tools = parse_tools(args.tools)
    with open(args.out, "w") as f:
        f.write(printer_cfg_text(tools, args.mcu_serial, args.frontend))
    print("wrote %s" % args.out)


# KlipperScreen keeps its own settings below this line and rewrites them
# (ks_includes/config.py); user sections go above it
KS_AUTOGEN = "#~# --- Do not edit below this line"
KS_COOLDOWN = (
    "# KlipperXL-Plus: Cooldown only zeroes Klipper heaters and the modular bed is\n"
    "# not one - turn it off too\n"
    "[preheat cooldown]\n"
    "gcode: M140 S0\n"
    "\n")


def cmd_klipperscreen(args):
    text = ""
    if os.path.exists(args.conf):
        with open(args.conf) as f:
            text = f.read()
    if re.search(r"^\[preheat cooldown\]", text, re.M):
        print("%s already has a [preheat cooldown] - left as it is (add"
              " M140 S0 to its gcode so Cooldown turns the bed off)"
              % (args.conf,))
        return
    i = text.find(KS_AUTOGEN)
    if i < 0:
        i = len(text)
        if text and not text.endswith("\n"):
            text += "\n"
            i += 1
    if text:
        shutil.copyfile(args.conf, args.conf + ".kxlplus-bak")
    with open(args.conf, "w") as f:
        f.write(text[:i] + KS_COOLDOWN + text[i:])
    print("added [preheat cooldown] (M140 S0) to %s" % (args.conf,))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("tools")
    t.add_argument("--tools", required=True)
    t.add_argument("--out", required=True)
    p = sub.add_parser("printer-cfg")
    p.add_argument("--tools", required=True)
    p.add_argument("--mcu-serial", required=True)
    p.add_argument("--frontend", default="mainsail", choices=("mainsail", "fluidd"))
    p.add_argument("--out", required=True)
    k = sub.add_parser("klipperscreen")
    k.add_argument("--conf", required=True)
    args = ap.parse_args()
    {"tools": cmd_tools, "printer-cfg": cmd_printer_cfg,
     "klipperscreen": cmd_klipperscreen}[args.cmd](args)


if __name__ == "__main__":
    main()
