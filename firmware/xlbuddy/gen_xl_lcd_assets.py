#!/usr/bin/env python3
# KlipperXL-Plus - xl_lcd_assets.bin -> xlplus_lcd_assets.c for the XLBuddy
# firmware (xlplus_lcd.c).  Run by build_xlbuddy_pi.sh; Python standard
# library only.
#
# xl_lcd_assets.bin (scripts/build_xl_lcd_assets.py, from Prusa-Firmware-Buddy
# 6.10.3's own PNGs): icons blended onto black as b, g, r and the
# LiberationMono 9x16 glyphs as 16 levels.  Here the icons the screen uses
# are run-length packed (a byte c < 128 = c + 1 literal pixels follow,
# c >= 128 = the next pixel c - 126 times; checked by decoding each one
# back) and the glyphs packed 2 levels per byte, high nibble first.  Fonts in
# the order the firmware and the host number them: 0 small, 1 normal, 2 big.
#
# Usage: gen_xl_lcd_assets.py xl_lcd_assets.bin > xlplus_lcd_assets.c
#
# Copyright (C) 2026  Richard Crook
#
