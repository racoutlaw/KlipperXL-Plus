import base64, json, sys, zlib

# Order = the icon ids; the host reads it from the XL_LCD_ICONS constant
ICONS = ['%s_80x80%s' % (n, v)
         for n in ('print', 'preheat', 'spool', 'calibrate', 'settings', 'info')
         for v in ('', '_focused')]
ICONS += ['home_shape_16x16', 'lan_16x16', 'usb_20x16', 'nozzle_16x16',
          'spool_16x16', 'enclosure_16x16']
# The print screen and the menus behind the tiles (owner 11/06)
ICONS += ['settings_80x80_disabled']
ICONS += ['%s_80x80%s' % (n, v)
          for n in ('pause', 'stop', 'resume', 'home', 'reprint')
          for v in ('', '_focused', '_disabled')]
ICONS += ['print_16x16', 'settings_16x16', 'preheat_white_16x16',
          'spool_white_16x16', 'calibrate_white_16x16', 'info_16x16',
          'move_16x16', 'home_full_16x16', 'folder_up_16x16',
          'folder_full_16x16', 'arrow_right_10x16', 'warning_48x48']
ICONS += ['big_%s' % (c,) for c in '0123456789%']
CHARS = [chr(c) for c in range(0x20, 0x7F)] + ['\xb0']   # 96 glyphs
FONTS = ('small', 'normal', 'big')


def rle(px):
    out, i, n = bytearray(), 0, len(px)
    while i < n:
        j = i + 1
        while j < n and px[j] == px[i] and j - i < 129:
            j += 1
        if j - i >= 2:
            out.append(126 + j - i)
            out += px[i]
            i = j
            continue
        lit = []
        while i < n and len(lit) < 128:
            if i + 1 < n and px[i + 1] == px[i]:
                break
            lit.append(px[i])
            i += 1
        out.append(len(lit) - 1)
        for p in lit:
            out += p
    return bytes(out)


def unrle(data, count):
    px, p = [], 0
    while len(px) < count:
        c = data[p]
        p += 1
        if c < 128:
            for _ in range(c + 1):
                px.append(data[p:p + 3])
                p += 3
        else:
            px.extend([data[p:p + 3]] * (c - 126))
            p += 3
    return px


def c_bytes(data, indent='    '):
    lines = []
    for i in range(0, len(data), 16):
        lines.append(indent + ', '.join('0x%02x' % b for b in data[i:i + 16])
                     + ',')
    return '\n'.join(lines)


def pack_font(font):
    # one glyph: w * h levels, 2 per byte, high nibble first
    fw, fh = font['w'], font['h']
    glyphs = []
    for ch in CHARS:
        lv = bytearray(base64.b64decode(font['glyphs'][str(ord(ch))]))
        if len(lv) != fw * fh:
            raise SystemExit("glyph 0x%02x is not %dx%d" % (ord(ch), fw, fh))
        if len(lv) % 2:
            lv.append(0)
        glyphs.append(bytes((lv[k] << 4) | lv[k + 1]
                            for k in range(0, len(lv), 2)))
    return fw, fh, (fw * fh + 1) // 2, glyphs


def main():
    with open(sys.argv[1], 'rb') as f:
        assets = json.loads(zlib.decompress(f.read()))
    index, blob, names = [], bytearray(), []
    for name in ICONS:
        w, h, b64 = assets['icons'][name]
        raw = base64.b64decode(b64)
        px = [raw[k:k + 3] for k in range(0, len(raw), 3)]
        packed = rle(px)
        if unrle(packed, w * h) != px:
            raise SystemExit("run-length check failed for %s" % (name,))
        index.append((w, h, len(blob), len(packed)))
        blob += packed
        names.append('%s:%d:%d' % (name, w, h))
    fonts = [pack_font(assets['fonts'][name]) for name in FONTS]
    if fonts[0][:2] != (9, 16):
        raise SystemExit("the small font is not 9x16")
    out = sys.stdout
    out.write("// Generated by gen_xl_lcd_assets.py from xl_lcd_assets.bin"
              " - do not edit\n// Prusa-Firmware-Buddy 6.10.3 icons and"
              " LiberationMono 9x16 (GPLv3 / OFL)\n")
    out.write('#include <stdint.h>\n#include "command.h" // DECL_CONSTANT_STR\n\n')
    out.write('DECL_CONSTANT_STR("XL_LCD_ICONS", "%s");\n\n' % (','.join(names),))
    out.write("const uint8_t xl_lcd_icon_count = %d;\n\n" % (len(index),))
    out.write("const uint32_t xl_lcd_icon_index[][4] = {\n")
    for name, (w, h, off, size) in zip(ICONS, index):
        out.write("    { %d, %d, %d, %d },   // %s\n" % (w, h, off, size, name))
    out.write("};\n\nconst uint8_t xl_lcd_icon_data[] = {\n%s\n};\n\n"
              % (c_bytes(blob),))
    for name, (fw, fh, nbytes, glyphs) in zip(FONTS, fonts):
        out.write("static const uint8_t font_%s[] = {   // %dx%d, %d bytes each\n"
                  % (name, fw, fh, nbytes))
        for ch, g in zip(CHARS, glyphs):
            out.write("    // 0x%02x\n%s\n" % (ord(ch), c_bytes(g)))
        out.write("};\n\n")
    out.write("const uint8_t xl_lcd_font_count = %d;\n" % (len(fonts),))
    out.write("const uint8_t xl_lcd_font_w[] = { %s };\n"
              % (', '.join(str(f[0]) for f in fonts),))
    out.write("const uint8_t xl_lcd_font_h[] = { %s };\n"
              % (', '.join(str(f[1]) for f in fonts),))
    out.write("const uint16_t xl_lcd_font_bytes[] = { %s };\n"
              % (', '.join(str(f[2]) for f in fonts),))
    out.write("const uint8_t * const xl_lcd_font_data[] = { %s };\n"
              % (', '.join('font_%s' % (n,) for n in FONTS),))
    sys.stderr.write("xlplus_lcd_assets.c: %d icons, %d bytes packed (%d raw),"
                     " %d fonts\n" % (len(index), len(blob),
                                      sum(w * h * 3 for w, h, _, _ in index),
                                      len(fonts)))


if __name__ == '__main__':
    main()
