#!/bin/bash
# =============================================================================
# KlipperXL-Plus - build the XLBuddy firmware on the printer's Pi, WITHOUT leaving
# the Klipper repo dirty
# Copyright (C) 2026 Richard Crook
#
# Same rule as KlipperXL's scripts/build_klipperxl.sh: Klipper has no hook for
# out-of-tree MCU sources, so the build line goes into the TRACKED
# src/stm32/Makefile only for the length of the build and is put back by a
# trap - on success, failure or interrupt.  The repo is clean at rest, so
# Moonraker reports Klipper clean and its updates apply normally.
#
# KlipperXL-Plus adds to the XLBuddy build:
#   src/stm32/xlplus_rs485.c   RS485 bridge engine (Dwarfs + modular bed)
#   src/stm32/xlplus_resets.c  PCA9557 Dwarf / bed reset lines
#   CONFIG_INITIAL_PINS="PE14" (xlbuddy.config)
# The .c files are copied in for the build and removed again by the trap.
#
# The build gets its own .config and output folder, so it never touches a
# ~/klipper/.config or ~/klipper/out/ that already exists.
#
# Refuses to produce an image that would not sit behind the Prusa bootloader:
# the application must start at 0x08020200 (NEVER 0x08000000).
#
# Firmware ID (owner 10/10, klippy/extras/xl_fw_check.py): a hash of the
# sources + xlbuddy.config + the build line is compiled in as the constant
# KXLPLUS_FW (a generated src/stm32/kxlplus_fw_id.c, removed by the trap like
# the sources) and written to BUILD_DIR/fw_id.  Klipper's version is not in it.
#
# Usage:  bash build_xlbuddy_pi.sh [BUILD_DIR]     (default ~/kxlplus-build/xlbuddy)
#         KLIPPER_DIR=~/klipper bash build_xlbuddy_pi.sh
# Output: BUILD_DIR/klipper.bin, BUILD_DIR/klipper.bbf, BUILD_DIR/klipper.dict,
#         BUILD_DIR/fw_id
# =============================================================================
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
KLIPPER_DIR="${KLIPPER_DIR:-$HOME/klipper}"
BUILD=${1:-$HOME/kxlplus-build/xlbuddy}
PACK_FW="$HERE/../../scripts/pack_fw.py"
PYTHON="${PYTHON:-$HOME/klippy-env/bin/python}"
SOURCES="xlplus_rs485.c xlplus_resets.c"
MAKE_LINE='src-$(CONFIG_MACH_STM32F4) += stm32/xlplus_rs485.c stm32/xlplus_resets.c'
ID_SRC=src/stm32/kxlplus_fw_id.c

cd "$KLIPPER_DIR" || { echo "ERROR: no such directory: $KLIPPER_DIR"; exit 1; }
[ -f src/stm32/Makefile ] || { echo "ERROR: $KLIPPER_DIR is not a Klipper tree"; exit 1; }
for f in $SOURCES xlbuddy.config; do
    [ -f "$HERE/$f" ] || { echo "ERROR: missing $HERE/$f"; exit 1; }
done
[ -f "$PACK_FW" ] || { echo "ERROR: missing $PACK_FW"; exit 1; }
FW_ID="xlbuddy-$( (cd "$HERE" && cat $SOURCES xlbuddy.config; echo "$MAKE_LINE") \
    | tr -d '\r' | sha256sum | cut -c1-12)"

# ---- already built? Same KlipperXL-Plus firmware ID + Klipper commit + compiler
# = the same firmware (only the build time differs) - owner 10/10
BUILD_KEY="$FW_ID $(git rev-parse HEAD) gcc-$(arm-none-eabi-gcc -dumpversion)"
if [ "${KXL_REBUILD:-0}" != "1" ] && [ -f "$BUILD/klipper.bbf" ] \
        && [ "$(cat "$BUILD/build_key" 2>/dev/null)" = "$BUILD_KEY" ]; then
    echo "UP TO DATE: $BUILD/klipper.bbf ($FW_ID, same Klipper + compiler)"
    echo "    not rebuilt (KXL_REBUILD=1 or the installer's --rebuild forces it)"
    exit 0
fi

# ---- refuse a tree that already has edits or leftovers we did not make
if ! git diff --quiet -- src/stm32/Makefile; then
    echo "ERROR: src/stm32/Makefile is already modified."
    echo "       Inspect it, then restore with: git checkout -- src/stm32/Makefile"
    exit 1
fi
for f in $SOURCES kxlplus_fw_id.c; do
    if [ -e "src/stm32/$f" ]; then
        echo "ERROR: src/stm32/$f already exists (left by an interrupted build?)."
        echo "       Remove it, then run this again."
        exit 1
    fi
done

# ---- ALWAYS put the tree back, even on a failed or interrupted build
restore_tree() {
    cd "$KLIPPER_DIR" 2>/dev/null || return
    git checkout -- src/stm32/Makefile 2>/dev/null || true
    for f in $SOURCES; do rm -f "src/stm32/$f"; done
    rm -f "$ID_SRC"
    echo "  Klipper tree restored - repo is clean, Klipper updates will work"
}
trap restore_tree EXIT INT TERM

echo "=== patching the build (temporarily) ==="
for f in $SOURCES; do cp "$HERE/$f" src/stm32/; echo "  + src/stm32/$f"; done
echo "$MAKE_LINE" >> src/stm32/Makefile; echo "  + src/stm32/Makefile build line"
cat > "$ID_SRC" <<EOF
// KlipperXL-Plus firmware ID - generated by build_xlbuddy_pi.sh, removed after it
#include "command.h" // DECL_CONSTANT_STR
DECL_CONSTANT_STR("KXLPLUS_FW", "$FW_ID");
EOF
echo 'src-$(CONFIG_MACH_STM32F4) += stm32/kxlplus_fw_id.c' >> src/stm32/Makefile
echo "  + firmware ID $FW_ID"

echo
echo "=== configuring ($BUILD) ==="
rm -rf "$BUILD"; mkdir -p "$BUILD"
cp "$HERE/xlbuddy.config" "$BUILD/.config"
MK="make KCONFIG_CONFIG=$BUILD/.config OUT=$BUILD/out/"
$MK olddefconfig >/dev/null
grep -q '^CONFIG_FLASH_APPLICATION_ADDRESS=0x8020200$' "$BUILD/.config" \
    || { echo "REFUSING: application address is not 0x8020200 (the Prusa bootloader must stay)"; exit 1; }
grep -q '^CONFIG_STM32_FLASH_START_0000=y' "$BUILD/.config" \
    && { echo "REFUSING: no-bootloader build (0x08000000)"; exit 1; }
grep -q '^CONFIG_INITIAL_PINS="PE14"$' "$BUILD/.config" \
    || { echo "REFUSING: CONFIG_INITIAL_PINS is not PE14"; exit 1; }

echo
echo "=== building ==="
$MK -j"$(nproc)"

echo
echo "=== verifying the KlipperXL-Plus bridge is compiled in ==="
"$PYTHON" - "$BUILD/out/klipper.dict" "$FW_ID" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
got = d.get("config", {}).get("KXLPLUS_FW")
if got != sys.argv[2]:
    print("  !! firmware ID %r in the build, expected %r" % (got, sys.argv[2]))
    print("     do NOT flash this binary")
    sys.exit(1)
print("  OK: firmware ID %s compiled in" % (got,))
# every DECL_COMMAND / sendf of xlplus_rs485.c and xlplus_resets.c
need_cmds = ["serial_bridge_write", "serial_bridge_append",
             "rs485_frame_load", "rs485_frame_send", "rs485_stats",
             "xl_reset_lines"]
need_resp = ["serial_bridge_read", "serial_bridge_done",
             "rs485_frame_read", "rs485_frame_done",
             "rs485_stats_a", "rs485_stats_b", "xl_reset_lines_result"]
cmds = [c.split()[0] for c in d["commands"]]
resp = [r.split()[0] for r in d["responses"]]
missing = [c for c in need_cmds if c not in cmds] + \
          [r for r in need_resp if r not in resp]
if missing:
    print("  !! missing from the firmware:", missing)
    print("     do NOT flash this binary")
    sys.exit(1)
print("  OK: bridge commands present; %d commands, version %s"
      % (len(d["commands"]), d.get("version")))
PY

echo
echo "=== packing the .bbf ==="
cp "$BUILD/out/klipper.bin" "$BUILD/klipper.bin"
cp "$BUILD/out/klipper.dict" "$BUILD/klipper.dict"
"$PYTHON" "$PACK_FW" "$BUILD/klipper.bin" --no-sign --version 1.0.0+1 \
    --printer-type 3 --printer-version 1 --printer-subversion 0 --bbf-version 2
[ -f "$BUILD/klipper.bbf" ] || { echo "ERROR: pack_fw.py made no .bbf"; exit 1; }
echo "$FW_ID" > "$BUILD/fw_id"
echo "$BUILD_KEY" > "$BUILD/build_key"

echo
echo "OK: $BUILD/klipper.bbf"
echo "    klipper.bin $(stat -c %s "$BUILD/klipper.bin") bytes, md5 $(md5sum < "$BUILD/klipper.bin" | cut -c1-8)"
echo "    Flash: copy klipper.bbf to a FAT32 USB stick, plug it into the printer,"
echo "    power-cycle (docs/INSTALL.md, section 4.3)."
